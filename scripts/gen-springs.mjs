// Generates src/springs.css: Apple-style springs as CSS `linear()` easings.
//
// Apple describes a spring by two numbers (WWDC23 "Animate with springs"):
//   duration – the perceptual duration (the spring's period), and
//   bounce   – 0 = no overshoot (critically damped), higher = bouncier.
// In physics terms (mass 1): angular frequency ω = 2π / duration, damping ratio ζ = 1 − bounce.
// SwiftUI's presets: .smooth (bounce 0), .snappy (small bounce), .bouncy (larger bounce).
// We sample the spring's step response and emit it as a linear() curve plus the time it takes to settle.
//
//   node scripts/gen-springs.mjs
import { writeFileSync } from "node:fs";

function spring(duration, bounce) {
  const w = (2 * Math.PI) / duration;
  const z = 1 - bounce;
  const x = (t) => {
    if (z >= 1) return 1 - (1 + w * t) * Math.exp(-w * t);
    const wd = w * Math.sqrt(1 - z * z);
    return 1 - Math.exp(-z * w * t) * (Math.cos(wd * t) + ((z * w) / wd) * Math.sin(wd * t));
  };
  // settle: last time |1 - x| > 0.002
  let settle = 0;
  for (let t = 0; t < 4; t += 0.002) if (Math.abs(1 - x(t)) > 0.002) settle = t;
  settle = Math.ceil(settle * 100) / 100;
  const n = 48;
  const pts = [];
  for (let i = 0; i <= n; i++) pts.push(+x((settle * i) / n).toFixed(4));
  pts[n] = 1;
  return { easing: `linear(${pts.join(", ")})`, dur: `${settle}s` };
}

const presets = {
  smooth: spring(0.5, 0), // default: no overshoot
  snappy: spring(0.4, 0.15), // quick, a hint of overshoot
  bouncy: spring(0.5, 0.3), // playful, visible overshoot
  quick: spring(0.3, 0.1), // small controls (presses, toggles)
};

let css = `/* Generated by scripts/gen-springs.mjs. Apple-style springs (duration, bounce) as CSS linear() easings. */\n`;
css += `:root {\n`;
// fallbacks for browsers without linear()
css += `  --ease-smooth: cubic-bezier(0.25, 1, 0.5, 1); --dur-smooth: 0.5s;\n`;
css += `  --ease-snappy: cubic-bezier(0.2, 0.9, 0.3, 1.1); --dur-snappy: 0.4s;\n`;
css += `  --ease-bouncy: cubic-bezier(0.3, 1.4, 0.5, 1); --dur-bouncy: 0.55s;\n`;
css += `  --ease-quick: cubic-bezier(0.25, 1, 0.5, 1); --dur-quick: 0.25s;\n`;
css += `}\n@supports (transition-timing-function: linear(0, 1)) {\n  :root {\n`;
for (const [name, p] of Object.entries(presets)) css += `    --ease-${name}: ${p.easing};\n    --dur-${name}: ${p.dur};\n`;
css += `  }\n}\n`;
writeFileSync(new URL("../src/springs.css", import.meta.url), css);
for (const [name, p] of Object.entries(presets)) console.log(name, p.dur, "max", Math.max(...p.easing.slice(7, -1).split(", ").map(Number)));
